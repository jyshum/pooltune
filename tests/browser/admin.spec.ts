import{test,expect}from'@playwright/test';
test('private setup, interrupted wizard, owner controls and logout use the actual API',async({page})=>{
 const seen:string[]=[];page.on('response',async response=>{if(response.url().startsWith('http://127.0.0.1:12163/api/')){try{seen.push(await response.text())}catch{}}});
 await page.goto('http://127.0.0.1:12163');
 await expect(page.getByRole('heading',{name:'Claim this installation'})).toBeVisible();
 await page.getByLabel('One-time setup token').fill('x'.repeat(43));
 await page.getByLabel('Administrator password').fill('browser fixture private password');
 await page.getByLabel('Administrator password').press('Tab');
 await expect(page.getByRole('button',{name:'Claim installation'})).toBeFocused();
 await page.keyboard.press('Enter');
 await expect(page.getByRole('heading',{name:'Make the boundaries explicit'})).toBeVisible();
 await page.getByLabel('Target ID').fill('Demo database');
 await page.getByLabel('Server connection profile').fill('fixture-db');
 await page.getByRole('button',{name:'Save connection draft'}).click();
 await expect(page.getByRole('status')).toHaveText('Change confirmed.');
 await page.getByRole('button',{name:'Verify saved connection'}).click();
 await expect(page.getByRole('heading',{name:'Observe the traffic you choose'})).toBeVisible();
 await page.reload();
 await expect(page.getByRole('heading',{name:'Observe the traffic you choose'})).toBeVisible();
 await page.getByRole('button',{name:'Read observed workloads'}).click();
 await page.getByLabel('Priority for Interactive lookup').selectOption('critical');
 await page.getByLabel('Lock this business priority').check();
 await expect(page.getByRole('button',{name:'Ask AI for a draft'})).toBeDisabled();
 await page.getByRole('button',{name:'Approve groups and initial policy'}).click();
 await expect(page.getByRole('button',{name:'Freeze automation'})).toBeVisible();
 await page.getByRole('button',{name:'Freeze automation'}).click();
 await expect(page.getByRole('button',{name:'Resume automation'})).toBeVisible();
 // Controlled health state checks the separate UI action and real auth/API route.
 await expect(page.getByRole('button',{name:'Resume traffic safely'})).toBeDisabled();
 await page.getByRole('button',{name:'Resume automation'}).click();
 await expect(page.getByRole('button',{name:'Resume traffic safely'})).toBeEnabled();
 await page.getByRole('button',{name:'Resume traffic safely'}).click();
 await expect(page.getByRole('button',{name:'Resume traffic safely'})).toHaveCount(0);
 await expect(page.getByRole('button',{name:'Release safety ceiling'})).toBeEnabled();
 await page.getByRole('button',{name:'Release safety ceiling'}).click();
 await expect(page.getByRole('button',{name:'Release safety ceiling'})).toHaveCount(0);
 await page.getByText('Restore a reviewed revision').click();
 await page.getByLabel('Revision to restore').fill('r2');
 await page.getByRole('button',{name:'Restore revision',exact:true}).click();
 await page.getByRole('button',{name:'History',exact:true}).click();
 await expect(page.getByRole('cell',{name:'freeze (controlled fixture)',exact:true})).toBeVisible();
 await expect(page.getByRole('cell',{name:'revert (controlled fixture)',exact:true})).toBeVisible();
 const session=await(await page.request.get('http://127.0.0.1:12163/api/session')).json();
 const denied=await page.request.post('http://127.0.0.1:12163/api/freeze',{headers:{Origin:'http://evil.example','X-CSRF-Token':session.csrf},data:{expected_revision:'r7',idempotency_key:'forged'}});expect(denied.status()).toBe(403);
 await page.screenshot({path:'test-results/admin-control.png',fullPage:true});
 expect(await page.evaluate(()=>Object.keys(localStorage))).toEqual([]);
 await page.getByRole('button',{name:'Sign out'}).click();
 await expect(page.getByRole('heading',{name:'Welcome back'})).toBeVisible();
 expect((await page.request.get('http://127.0.0.1:12163/api/state')).status()).toBe(401);
 await page.getByLabel('Administrator password').fill('browser fixture private password');
 await page.getByRole('button',{name:'Sign in',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Demo database'})).toBeVisible();
 const nextSession=await(await page.request.get('http://127.0.0.1:12163/api/session')).json();
 await page.request.post('http://127.0.0.1:12163/api/logout-all',{headers:{Origin:'http://127.0.0.1:12163','X-CSRF-Token':nextSession.csrf},data:{}});
 await expect(page.getByRole('heading',{name:'Welcome back'})).toBeVisible({timeout:7000});
 expect(seen.join('\n')).not.toContain('browser fixture private password');
 expect(seen.join('\n')).not.toContain('x'.repeat(43));
});
